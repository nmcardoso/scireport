"""JSON Schemas for the data file, generated from the pydantic models (ADR-0008).

The frozen schema of each spec version lives in ``scireport/spec/schemas/`` and a test fails when
the models drift from it. The schema describes the canonical manifest, in which every value is an
envelope; loaders also accept the bare-JSON shorthand of :mod:`scireport.spec.kinds`, and a
hand-authored directory may leave out asset hashes.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from scireport.errors import SpecVersionError
from scireport.spec.manifest import Manifest
from scireport.spec.version import SPEC_VERSION, parse_version

SCHEMA_DIR = Path(__file__).resolve().parent / 'schemas'
"""Folder with the frozen schema files, shipped as package data."""

SCHEMA_ID = 'https://nmcardoso.github.io/scireport/schemas/data-{version}.schema.json'


def schema_filename(version: str = SPEC_VERSION) -> str:
  """Return the file name of the schema for a spec version.

  Parameters
  ----------
  version : str, default=SPEC_VERSION
      A spec version such as ``'1.0'``.

  Returns
  -------
  str
      For example ``data-1.0.schema.json``.
  """
  return f'data-{version}.schema.json'


def manifest_json_schema(version: str = SPEC_VERSION) -> dict[str, Any]:
  """Generate the JSON Schema of the manifest for a spec version this scireport reads.

  The models describe the newest version. A field, or a whole model, added in a later minor
  version carries ``json_schema_extra={'since': 'MAJOR.MINOR'}``; the schema of an older version
  leaves those out (see :func:`schema_for_version`), so that the frozen file of every released
  version can be regenerated and compared byte for byte.

  Parameters
  ----------
  version : str, default=SPEC_VERSION
      A spec version of the current major that is not newer than :data:`SPEC_VERSION`.

  Returns
  -------
  dict
      A JSON Schema (draft 2020-12) document.

  Raises
  ------
  SpecVersionError
      With code ``E501`` when ``version`` is newer than this scireport, or ``E503`` when it is of
      an older major (use the frozen file with :func:`load_frozen_schema`).
  """
  wanted = parse_version(version)
  newest = parse_version(SPEC_VERSION)
  if wanted > newest:
    raise SpecVersionError(
      f'cannot generate the schema of spec {version}; this scireport writes {SPEC_VERSION}',
      code='E501',
    )
  if wanted[0] != newest[0]:
    raise SpecVersionError(
      f'cannot generate the schema of spec {version}; this scireport writes {SPEC_VERSION}',
      code='E503',
      hint='Read the frozen file of that version with load_frozen_schema.',
    )
  schema: dict[str, Any] = schema_for_version(Manifest.model_json_schema(), version)
  schema = {
    '$schema': 'https://json-schema.org/draft/2020-12/schema',
    '$id': SCHEMA_ID.format(version=version),
    **schema,
  }
  schema['title'] = f'scireport data file {version}'
  schema['description'] = (
    'The canonical manifest (scireport.json) of a scireport bundle. Every value is an envelope '
    'with a "kind". Loaders also accept bare JSON as shorthand (a string is text, a number is a '
    'number, an array is a list, an object without "kind" is a mapping) and, in hand-authored '
    'directories, asset references without sha256 and bytes.'
  )
  schema['properties']['scireport'] = {
    'const': version,
    'type': 'string',
    'description': 'Spec version, MAJOR.MINOR.',
  }
  schema['properties']['values']['additionalProperties'] = False
  return schema


def schema_for_version(schema: dict[str, Any], version: str) -> dict[str, Any]:
  """Remove what a later minor version added from a schema generated by the models.

  A property, a definition or a union member whose schema has ``"since": "MAJOR.MINOR"`` newer
  than ``version`` is dropped, together with the references to it; the ``since`` markers
  themselves never appear in the result.

  Parameters
  ----------
  schema : dict
      A pydantic-generated schema; it is not changed.
  version : str
      The spec version the result should describe.

  Returns
  -------
  dict
      A copy without the later additions.
  """
  wanted = parse_version(version)
  result: dict[str, Any] = json.loads(json.dumps(schema))
  defs: dict[str, Any] = result.get('$defs', {})
  gone = {name for name, node in defs.items() if _is_newer(node, wanted)}
  _prune(result, wanted, gone)
  for name in gone:
    del defs[name]
  return result


def _is_newer(node: Any, wanted: tuple[int, int]) -> bool:
  """Whether a schema node was added after ``wanted`` (it has a later ``since``)."""
  return isinstance(node, dict) and 'since' in node and parse_version(node['since']) > wanted


def _is_gone(node: Any, wanted: tuple[int, int], gone: set[str]) -> bool:
  """Whether a node is newer than ``wanted`` or refers to a definition that is."""
  if _is_newer(node, wanted):
    return True
  return isinstance(node, dict) and node.get('$ref', '').rpartition('/')[2] in gone


def _prune(node: Any, wanted: tuple[int, int], gone: set[str]) -> None:
  """Drop, in place, every later addition below ``node``."""
  if isinstance(node, list):
    for item in node:
      _prune(item, wanted, gone)
    return
  if not isinstance(node, dict):
    return
  node.pop('since', None)
  for key in ('oneOf', 'anyOf', 'allOf'):
    if key in node:
      node[key] = [item for item in node[key] if not _is_gone(item, wanted, gone)]
  mapping = node.get('discriminator', {}).get('mapping')
  if mapping:
    node['discriminator']['mapping'] = {
      tag: ref for tag, ref in mapping.items() if ref.rpartition('/')[2] not in gone
    }
  properties = node.get('properties')
  if isinstance(properties, dict):
    dropped = [name for name, prop in properties.items() if _is_gone(prop, wanted, gone)]
    for name in dropped:
      del properties[name]
    if 'required' in node:
      node['required'] = [name for name in node['required'] if name not in dropped]
  for child in node.values():
    _prune(child, wanted, gone)


def schema_text(schema: dict[str, Any]) -> str:
  """Serialise a schema the way the frozen files are stored.

  Parameters
  ----------
  schema : dict
      A schema from :func:`manifest_json_schema`.

  Returns
  -------
  str
      Two-space-indented JSON with sorted keys, ending in a newline.
  """
  return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def load_frozen_schema(version: str = SPEC_VERSION) -> dict[str, Any]:
  """Load the frozen schema file of a spec version.

  Parameters
  ----------
  version : str, default=SPEC_VERSION
      A spec version such as ``'1.0'``.

  Returns
  -------
  dict
      The schema as stored in the package.

  Raises
  ------
  FileNotFoundError
      When no schema was frozen for ``version``.
  """
  path = SCHEMA_DIR / schema_filename(version)
  loaded: dict[str, Any] = json.loads(path.read_text(encoding='utf-8'))
  return loaded
