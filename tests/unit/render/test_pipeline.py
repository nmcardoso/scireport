def test_write_puts_the_files_on_disk(tmp_path: Path) -> None:
  result = render_bundle(kitchen_sink(), formats=['md', 'tex'])
  written = result.write(tmp_path / 'out')
  assert (tmp_path / 'out' / 'md' / 'index.md').read_bytes() == result.files['md/index.md']
  assert (tmp_path / 'out' / 'tex' / 'figures' / 'figures.curve.pdf').is_file()
  assert len(written) == len(result.files)
  assert all(path.is_file() for path in written)


def test_a_template_syntax_error_has_a_file_and_line(tmp_path: Path) -> None:
  issues = render_issues(small(), 'ok\n{% if %}\n', 'md', tmp_path)
  assert codes(issues) == ['E704']
  assert issues[0].location == 'report.j2:2'


def small() -> Bundle:
  return Report('T').add_text('t', 'x').build()


def test_runtime_template_errors_are_coded(tmp_path: Path) -> None:
  cases = {
    '{{ nope }}': 'E803',
    "{{ ''.__class__ }}": 'E802',
    '{{ 1 / 0 }}': 'E804',
    '{{ data.t.nope }}': 'E803',
  }
  for body, code in cases.items():
    issues = render_issues(small(), body, 'md', tmp_path)
    errors = [i for i in issues if i.severity == 'error']
    assert codes(errors) == [code], body
    assert errors[0].location == 'report.j2:1'


def test_an_error_in_one_format_fails_the_whole_render(tmp_path: Path) -> None:
  template = write_template(tmp_path / 't', body='{{ c.text(data.t) }}')
  (template / 'report.tex.j2').write_text('((( nope )))', encoding='utf-8')
  with pytest.raises(RenderError) as caught:
    render_bundle(Report('T').add_text('t', 'x').build(), template=template, layout='minimal')
  assert codes(caught.value.issues) == ['E803']
  assert caught.value.issues[0].location == 'report.tex.j2:1'


def test_a_per_format_override_replaces_the_neutral_body(tmp_path: Path) -> None:
  template = write_template(tmp_path / 't', body='neutral {{ c.math("x") }}')
  (template / 'report.tex.j2').write_text(
    r'\textbf{(((meta.title)))} ((( c.math("y") )))', encoding='utf-8'
  )
  result = render_bundle(
    Report('T').add_text('t', 'x').build(), template=template, layout='minimal'
  )
  assert 'neutral' in result.files['md/report.md'].decode()
  assert r'\textbf{T} $y$' in result.files['tex/report.tex'].decode()


def test_a_template_for_other_specs_or_formats_is_refused(tmp_path: Path) -> None:
  old = write_template(tmp_path / 'a', body='x')
  (old / 'template.yaml').write_text(
    'spec: ">=2.0"\nname: old\nversion: 1\nformats: [md]\n', encoding='utf-8'
  )
  bundle = Report('T').add_text('t', 'x').build()
  with pytest.raises(RenderError) as caught:
    render_bundle(bundle, template=old, layout='minimal', formats=['html'])
  assert sorted(codes(caught.value.issues)) == ['E505', 'E706']
  assert 'supports data-file spec >=2.0' in caught.value.issues[0].message


def test_a_layout_missing_a_component_is_reported_before_rendering(tmp_path: Path) -> None:
  layout = write_layout(tmp_path / 'lay')
  components = layout / 'md' / 'components.md.j2'
  components.write_text(
    components.read_text(encoding='utf-8').replace('macro flow(', 'macro flux('), encoding='utf-8'
  )
  with pytest.raises(RenderError) as caught:
    render_bundle(Report('T').add_text('t', 'x').build(), layout=layout, formats=['md'])
  assert codes(caught.value.issues) == ['E707']
  assert "'flow'" in caught.value.issues[0].message


def test_a_layout_syntax_error_is_reported(tmp_path: Path) -> None:
  layout = write_layout(tmp_path / 'lay')
  (layout / 'html' / 'document.html.j2').write_text('{% if %}', encoding='utf-8')
  with pytest.raises(RenderError) as caught:
    render_bundle(Report('T').add_text('t', 'x').build(), layout=layout, formats=['html'])
  assert 'E704' in codes(caught.value.issues)
  assert caught.value.issues[0].location == 'html/document.html.j2:1'


def test_check_bundle_reports_what_only_a_render_shows(tmp_path: Path) -> None:
  report = (
    Report('T')
    .add_text('a', 'x')
    .add_text('b', 'y')
    .add_text('p', '# head\n\ntext', format='markdown')
  )
  report.set_outline(['a', 'p'])
  found = check_bundle(report.build(), formats=['html'])
  assert sorted(i.code for i in found.issues) == ['W401', 'W701']
  assert found.ok
  assert check_bundle(report.build(), formats=['html'], strict=True).exit_code == 2
  assert [i.code for i in check_bundle(report.build(), formats=['html'], render=False).issues] == []


def test_check_bundle_stops_at_static_errors() -> None:
  report = Report('T').add_text('a', 'x')
  report.set_render(layout='minimal@1')
  found = check_bundle(report.build(), template='generic@1', options={'bogus': 1})
  assert [i.code for i in found.issues] == ['E806'] and not found.ok


def test_dynamic_keys_are_warned_about_unless_the_template_declares_them(tmp_path: Path) -> None:
  body = "{% for k in keys('a') %}{{ c.value(v(k)) }}{% endfor %}"
  bundle = Report('T').add_text('a.x', 'x').build()
  assert 'W403' in report_of(bundle, body, 'md', tmp_path)
  template = write_template(tmp_path / 'declared', body=body, extra='dynamic_keys: true')
  found = check_bundle(bundle, template=template, layout='minimal', formats=['md'])
  assert found.issues == ()
