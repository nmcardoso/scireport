def codes(issues: Sequence[Issue]) -> list[str]:
  return [i.code for i in issues]


def test_every_format_is_written_into_its_own_folder() -> None:
  result = render_bundle(kitchen_sink())
  assert result.formats == ('md', 'html', 'tex')
  assert sorted(result.files) == [
    'html/report.html',
    'md/attachments/all_rows.csv',
    'md/data.md',
    'md/figures/figures.curve.png',
    'md/images/figures.logo.png',
    'md/index.md',
    'render-manifest.json',
    'tex/attachments/all_rows.csv',
    'tex/figures/figures.curve.pdf',
    'tex/images/figures.logo.png',
    'tex/latexmkrc',
    'tex/report.tex',
    'tex/scireport-minimal.sty',
  ]
  assert result.issues == ()


def test_two_renders_are_byte_identical() -> None:
  first = render_bundle(kitchen_sink())
  second = render_bundle(kitchen_sink())
  assert first.files == second.files
  assert list(first.files) == sorted(first.files)


def test_output_has_no_clock_and_no_absolute_paths() -> None:
  result = render_bundle(kitchen_sink())
  for name, data in result.files.items():
    if not name.endswith(('.md', '.html', '.tex', '.sty', '.json', 'latexmkrc', '.csv')):
      continue
    text = data.decode('utf-8')
    assert '/home/' not in text and '/tmp/' not in text, name
    assert '\r' not in text, name


def test_the_render_manifest_records_inputs_versions_and_outputs() -> None:
  result = render_bundle(kitchen_sink())
  manifest = json.loads(result.files[MANIFEST_NAME])
  assert manifest == result.manifest
  assert manifest['spec'] == '1.0'
  assert manifest['template']['ref'] == 'generic@1' and len(manifest['template']['sha256']) == 64
  assert manifest['layout']['ref'] == 'minimal@1'
  assert manifest['formats'] == ['md', 'html', 'tex']
  assert manifest['engines']['markup'] == 'mistletoe'
  assert manifest['engines']['latex'] == 'lualatex'
  assert manifest['options']['toc'] is True
  assert set(manifest['input']['assets']) >= {'assets/figures/figures.curve.png'}
  assert manifest['outputs']['md/index.md']['bytes'] == len(result.files['md/index.md'])
  assert MANIFEST_NAME not in manifest['outputs']
  assert manifest['warnings'] == []


def test_the_manifest_changes_when_the_content_changes() -> None:
  one = render_bundle(kitchen_sink()).manifest['input']['manifest_sha256']
  two = render_bundle(kitchen_sink(outline=False)).manifest['input']['manifest_sha256']
  assert one != two


def test_markdown_splits_when_a_chapter_names_a_file() -> None:
  split = render_bundle(kitchen_sink(), formats=['md'])
  assert 'md/data.md' in split.files and 'md/index.md' in split.files
  single = render_bundle(kitchen_sink(), formats=['md'], md_split=False)
  assert 'md/data.md' not in single.files and 'md/report.md' in single.files
  text = single.files['md/report.md'].decode()
  assert '\n## Data\n' in text and '\n## Facts\n' in text
  index = split.files['md/index.md'].decode()
  assert '[2 Data](data.md#data)' in index
  assert split.files['md/data.md'].decode().startswith('<!-- Generated by scireport')
  assert '\n# Data\n' in split.files['md/data.md'].decode()


def test_forcing_a_split_without_files_still_writes_an_index() -> None:
  result = render_bundle(kitchen_sink(split=False), formats=['md'], md_split=True)
  assert 'md/index.md' in result.files and 'md/data.md' not in result.files


def test_flat_output_needs_one_format() -> None:
  result = render_bundle(kitchen_sink(), formats=['html'], flat=True)
  assert sorted(result.files) == ['render-manifest.json', 'report.html']
  with pytest.raises(TemplateError) as caught:
    render_bundle(kitchen_sink(), flat=True)
  assert caught.value.code == 'E801'


